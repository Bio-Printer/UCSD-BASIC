#!/usr/bin/env python3
"""mkdecls.py -- bc/bcprocs.bas: a DECLARE for each procedure of the
compiler that another module calls (the compiler needs a DECLARE for a
procedure it does not see defined in the module it compiles).

  mkdecls.py bc/bc.bas bc/bclex.bas ... > bc/bcprocs.bas
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bas2c


def main(files):
    defs = {}          # name -> (module, header text)
    uses = {}          # module -> set of ID names
    for f in files:
        mod = os.path.basename(f).upper()
        src = open(f, encoding='latin1').read().split('\n')
        for l in src:
            m = re.match(r'\s*(PRIVATE\s+)?(SUB|FUNCTION)\s+([A-Za-z_][A-Za-z0-9_]*[$%!#]?)(.*)$', l, re.I)
            if m and not m.group(1):
                hdr = '%s %s%s' % (m.group(2).upper(), m.group(3), m.group(4).split("'")[0].rstrip())
                hdr = re.sub(r'\s+STATIC\s*$', '', hdr, flags=re.I)
                defs[m.group(3).upper()] = (mod, hdr)
        toks = bas2c.lex_line  # (unused: names are found by a scan of the text)
        u = set()
        for l in src:
            l = l[:bas2c.comment_at(l)]
            l = re.sub(r'"[^"]*"', '""', l)
            for w in re.findall(r'[A-Za-z_][A-Za-z0-9_]*[$%!#]?', l):
                u.add(w.upper())
        uses[mod] = u
    out = ["' BCPROCS -- generated by tools/mkdecls.py: the procedures of the",
           "' compiler that are called from another module"]
    for name in sorted(defs):
        mod, hdr = defs[name]
        if any(name in u for m, u in uses.items() if m != mod):
            out.append('DECLARE ' + hdr)
    print('\n'.join(out))


if __name__ == '__main__':
    main(sys.argv[1:])
